# ====================================================================
# Score thresholds — broad floors, not exact targets
# ====================================================================

class TestScoreFloors:
    """Scores should stay above minimum viable thresholds.

    These floors are deliberately low — they catch regressions where
    the placer produces garbage, not where it produces suboptimal
    placements. Raise them as the placer improves.
    """

    def test_usb_mcu_score_above_floor(self, usb_mcu):
        s, _ = usb_mcu
        assert s.score > 20.0, f"USB MCU score {s.score:.1f} below floor 20"

    def test_sensor_array_score_above_floor(self, sensor_array):
        s, _ = sensor_array
        assert s.score > 20.0, f"Sensor array score {s.score:.1f} below floor 20"

    def test_power_board_score_above_floor(self, power_board):
        s, _ = power_board
        assert s.score > 20.0, f"Power board score {s.score:.1f} below floor 20"

    def test_ui_board_score_above_floor(self, ui_board):
        s, _ = ui_board
        assert s.score > 15.0, f"UI board score {s.score:.1f} below floor 15"

    def test_rf_board_score_above_floor(self, rf_board):
        s, _ = rf_board
        assert s.score > 20.0, f"RF board score {s.score:.1f} below floor 20"


# ====================================================================
# Risky nets — power/ground always present, named sensibly
# ====================================================================

class TestRiskyNets:
    """Top risky nets should include power/ground (they span the board)
    and should have real net names, not auto-generated placeholders."""

    def test_usb_mcu_risky_nets_include_power(self, usb_mcu):
        s, _ = usb_mcu
        top = s.top_risky_net_names(5)
        assert "GND" in top or "VCC" in top, f"No power net in top 5 risky: {top}"

    def test_sensor_array_risky_nets_include_power(self, sensor_array):
        s, _ = sensor_array
        top = s.top_risky_net_names(5)
        assert "GND" in top or "VCC" in top

    def test_power_board_risky_nets_include_gnd(self, power_board):
        s, _ = power_board
        top = s.top_risky_net_names(5)
        assert "GND" in top, f"GND not in top 5 risky: {top}"

    def test_rf_board_risky_nets_include_power(self, rf_board):
        s, _ = rf_board
        top = s.top_risky_net_names(5)
        assert "GND" in top or "VCC" in top

    def test_risky_net_names_are_not_autogenerated(self, usb_mcu):
        s, _ = usb_mcu
        for name, _ in s.risky_nets:
            assert not name.startswith("_N"), f"Auto-generated net name in risky: {name}"


