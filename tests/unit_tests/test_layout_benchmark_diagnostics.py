# ====================================================================
# Warnings — sanity check that warnings are strings, not garbage
# ====================================================================

class TestWarnings:
    """Warnings should be well-formed strings when present."""

    def test_warnings_are_strings(self, usb_mcu):
        s, _ = usb_mcu
        for w in s.warnings:
            assert isinstance(w, str)
            assert len(w) > 5, f"Warning too short to be useful: {w!r}"

    def test_warnings_mention_refs(self, usb_mcu):
        s, _ = usb_mcu
        for w in s.warnings:
            has_ref = any(c.isupper() and c.isalpha() for c in w[:5])
            has_colon = ":" in w
            assert has_ref or has_colon or "mm" in w, (
                f"Warning doesn't look like a part diagnostic: {w!r}"
            )


# ====================================================================
# Oneliner — quick triage output for CI logs
# ====================================================================

class TestOneliner:
    """The oneliner summary should be parseable and informative."""

    def test_oneliner_includes_score(self, usb_mcu):
        s, _ = usb_mcu
        line = s.oneliner()
        assert "/100" in line

    def test_oneliner_includes_part_count(self, usb_mcu):
        s, _ = usb_mcu
        line = s.oneliner()
        assert "15/15" in line

    def test_oneliner_includes_case_name(self, sensor_array):
        s, _ = sensor_array
        assert "sensor_array" in s.oneliner()

    def test_all_cases_produce_oneliners(
        self, usb_mcu, sensor_array, power_board, ui_board, rf_board
    ):
        for s, _ in [usb_mcu, sensor_array, power_board, ui_board, rf_board]:
            line = s.oneliner()
            assert "/100" in line
            assert "parts" in line
