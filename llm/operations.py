# Operation 2: exception review -> candidate choices
# --------------------------------------------------------------------------

_INTERNAL_REVIEW_SYSTEM = (
    "You are reviewing structured PCB design exceptions raised by an automated "
    "board-generation engine. Each exception lists machine-applicable correction "
    "candidates. For EACH exception, pick exactly ONE candidate by id. Prefer the "
    "cheapest candidate that plausibly fixes the root cause. Do not repeat a "
    "correction listed in the prior-corrections history — it already failed or was "
    "already applied.\n"
    "\n"
    "STRICT OUTPUT REQUIREMENT: Output ONLY a JSON array of objects of the form "
    '{"exception_id": "...", "candidate_id": "..."} — one entry per exception, '
    "no markdown fences, no commentary."
)

_EXTERNAL_REVIEW_SYSTEM = (
    "You are a third-party engineering agent using a PCB generation API. The API "
    "exposes two tools: generate_design(spec) runs the full schematic+layout "
    "pipeline on a JSON circuit spec and returns design exceptions; "
    "apply_correction(exception_id, candidate_id) mutates the spec with the chosen "
    "candidate's action and lets you regenerate. Your last generate_design call "
    "returned the exceptions below; decide which correction candidate to apply for "
    "each exception. Pick exactly ONE candidate id per exception, preferring cheap "
    "fixes that address the root cause, and never repeating a correction from the "
    "prior-corrections history.\n"
    "\n"
    "STRICT OUTPUT REQUIREMENT: Output ONLY a JSON array of objects of the form "
    '{"exception_id": "...", "candidate_id": "..."} — one entry per exception, '
    "no markdown fences, no commentary."
)


def _as_dict(obj: Any) -> dict:
    return obj.model_dump() if hasattr(obj, "model_dump") else dict(obj)


def _render_exceptions(exceptions: list[dict]) -> str:
    lines = []
    for exc in exceptions:
        code = exc.get("code", "")
        sev = exc.get("severity", "")
        head = f"{exc['id']} [{code}]"
        if sev:
            head += f" ({sev})"
        lines.append(f"{head}: {exc.get('message', '')}")
        for cand in exc.get("candidates", []):
            tags = [
                f"{key}={cand[key]}"
                for key in ("action", "cost_hint")
                if cand.get(key)
            ]
            extra = f" ({', '.join(tags)})" if tags else ""
            lines.append(f"  {cand['id']}: {cand.get('human_summary', '')}{extra}")
    return "\n".join(lines)


def _validate_choices(raw: Any, valid: dict[str, set[str]]) -> Optional[list[dict]]:
    """Return normalized choices if raw covers every exception with a valid
    candidate id, else None."""
    if not isinstance(raw, list):
        return None
    picked: dict[str, str] = {}
    for item in raw:
        if not isinstance(item, dict):
            return None
        exc_id = item.get("exception_id")
        cand_id = item.get("candidate_id")
        if exc_id not in valid or cand_id not in valid[exc_id]:
            return None
        picked[exc_id] = cand_id
    if set(picked) != set(valid):
        return None
    return [{"exception_id": e, "candidate_id": picked[e]} for e in valid]


async def _review(
    exceptions: list[dict],
    board_context: dict,
    history: list[str],
    system_prompt: str,
    stage: str,
    model: Optional[str],
    spend_tracker: Any,
    client: Any,
) -> tuple[list[dict], list[dict], bool]:
    model = model or config.REVIEW_MODEL
    exceptions = [_as_dict(e) for e in exceptions]
    valid = {
        e["id"]: {c["id"] for c in e.get("candidates", [])} for e in exceptions
    }

    context_block = json.dumps(board_context, separators=(",", ":"), default=str)
    history_block = (
        "Prior corrections already applied this run (do NOT repeat these):\n"
        + "\n".join(f"- {h}" for h in history)
        if history
        else "No prior corrections this run."
    )
    messages = [
        {"role": "system", "content": system_prompt},
        {
            "role": "user",
            "content": (
                f"Board context:\n{context_block}\n\n"
                f"{history_block}\n\n"
                f"Design exceptions and their correction candidates:\n"
                f"{_render_exceptions(exceptions)}\n\n"
                "Pick one candidate per exception. JSON array only."
            ),
        },
    ]

    stages: list[dict] = []

    async def _attempt(msgs: list[dict]):
        resp = await complete(
            msgs, model, spend_tracker=spend_tracker, client=client
        )
        stages.append(_stage_dict(stage, resp))
        return resp

    resp = await _attempt(messages)
    try:
        raw = _loads_forgiving(resp.text, opener="[", closer="]")
    except ValueError:
        raw = None
    choices = _validate_choices(raw, valid)
    if choices is not None:
        return choices, stages, False

    valid_listing = "; ".join(
        f"{exc_id}: [{', '.join(sorted(cands))}]" for exc_id, cands in valid.items()
    )
    repair_messages = messages + [
        {"role": "assistant", "content": resp.text},
        {
            "role": "user",
            "content": (
                "Your previous answer was invalid. The only valid ids are — "
                f"{valid_listing}. Return a JSON array with exactly one entry per "
                'exception, each of the form {"exception_id": "...", '
                '"candidate_id": "..."}. JSON array only.'
            ),
        },
    ]
    resp2 = await _attempt(repair_messages)
    try:
        raw2 = _loads_forgiving(resp2.text, opener="[", closer="]")
    except ValueError:
        raw2 = None
    choices = _validate_choices(raw2, valid)
    if choices is not None:
        return choices, stages, False

    # Deterministic fallback: first candidate (c1, the deterministic-policy pick).
    fallback = []
    for e in exceptions:
        cands = e.get("candidates", [])
        fallback.append(
            {
                "exception_id": e["id"],
                "candidate_id": cands[0]["id"] if cands else "c1",
            }
        )
    return fallback, stages, True


async def review_exceptions(
    exceptions: list[dict],
    board_context: dict,
    history: list[str],
    model: Optional[str] = None,
    spend_tracker: Any = None,
    client: Any = None,
    stage: str = "review_internal",
) -> tuple[list[dict], list[dict], bool]:
    """Pick a correction candidate for each exception.

    Returns (choices, stage_dicts, fallback_used). choices is a list of
    {"exception_id", "candidate_id"}; fallback_used is True when both LLM
    attempts were invalid and c1 was picked deterministically for every
    exception.
    """
    return await _review(
        exceptions,
        board_context,
        history,
        system_prompt=_INTERNAL_REVIEW_SYSTEM,
        stage=stage,
        model=model,
        spend_tracker=spend_tracker,
        client=client,
    )


async def external_agent_review(
    exceptions: list[dict],
    board_context: dict,
    history: list[str],
    model: Optional[str] = None,
    spend_tracker: Any = None,
    client: Any = None,
    stage: str = "review_external",
) -> tuple[list[dict], list[dict], bool]:
    """Same contract as review_exceptions, but framed as a third-party agent
    consuming the PCB generation API (generate_design / apply_correction)."""
    return await _review(
        exceptions,
        board_context,
        history,
        system_prompt=_EXTERNAL_REVIEW_SYSTEM,
        stage=stage,
        model=model,
        spend_tracker=spend_tracker,
        client=client,
    )
