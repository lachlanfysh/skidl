def _load_worked_examples() -> list[dict]:
    examples = []
    for rel in WORKED_EXAMPLE_PATHS:
        path = _REPO_ROOT / rel
        if path.is_file():
            try:
                examples.append(json.loads(path.read_text()))
            except (OSError, ValueError):
                continue
    return examples or [_INLINE_EXAMPLE]


# --------------------------------------------------------------------------
# Forgiving JSON extraction
# --------------------------------------------------------------------------

def _strip_fences(text: str) -> str:
    """Strip markdown code fences and surrounding noise from model output."""
    t = text.strip()
    if t.startswith("```"):
        first_nl = t.find("\n")
        t = t[first_nl + 1 :] if first_nl != -1 else ""
        t = t.strip()
    if t.endswith("```"):
        t = t[:-3].strip()
    return t


def _loads_forgiving(text: str, opener: str = "{", closer: str = "}") -> Any:
    """json.loads with fence stripping; falls back to the outermost
    opener...closer slice if there is surrounding commentary."""
    t = _strip_fences(text)
    try:
        return json.loads(t)
    except ValueError:
        start, end = t.find(opener), t.rfind(closer)
        if start == -1 or end <= start:
            raise
        return json.loads(t[start : end + 1])


def _stage_dict(stage: str, resp) -> dict:
    return {
        "stage": stage,
        "model": resp.model,
        "tokens_in": resp.tokens_in,
        "tokens_out": resp.tokens_out,
        "latency_s": resp.latency_s,
        "cost_usd": resp.cost_usd,
    }


# --------------------------------------------------------------------------
# Operation 1: marketing text -> CircuitSpec
# --------------------------------------------------------------------------

async def nl_to_input_spec(
    marketing_text: str,
    board_id: str,
    model: Optional[str] = None,
    spend_tracker: Any = None,
    client: Any = None,
) -> tuple[CircuitSpec, list[dict]]:
    """Turn marketing text into a validated CircuitSpec.

    Returns (spec, stage_dicts). One completion plus at most one repair call;
    raises SpecParseError (carrying all stage dicts) if both fail.
    """
    model = model or config.DESIGN_MODEL
    examples = _load_worked_examples()
    examples_block = "\n\n".join(
        f"Worked example {i + 1} (a complete valid CircuitSpec):\n"
        + json.dumps(ex, separators=(",", ":"))
        for i, ex in enumerate(examples)
    )
    messages = [
        {"role": "system", "content": SPEC_SCHEMA_PROMPT + "\n\n" + examples_block},
        {
            "role": "user",
            "content": (
                f"Board id: {board_id}\n\n"
                f"Marketing description:\n{marketing_text}\n\n"
                "Produce the complete CircuitSpec JSON object for this board now. "
                "Include every IC, connector, passive, and decoupling capacitor. "
                "JSON object only."
            ),
        },
    ]

    stages: list[dict] = []

    async def _attempt(msgs: list[dict]):
        resp = await complete(
            msgs,
            model,
            response_format={"type": "json_object"},
            spend_tracker=spend_tracker,
            client=client,
        )
        stages.append(_stage_dict("design_nl_to_input", resp))
        return resp

    resp = await _attempt(messages)
    try:
        return CircuitSpec.model_validate(_loads_forgiving(resp.text)), stages
    except (ValueError, ValidationError) as err:
        error_text = str(err)

    repair_messages = messages + [
        {"role": "assistant", "content": resp.text},
        {
            "role": "user",
            "content": (
                f"Your previous output failed validation with this error:\n{error_text}\n\n"
                "Return the corrected complete JSON object only."
            ),
        },
    ]
    resp2 = await _attempt(repair_messages)
    try:
        return CircuitSpec.model_validate(_loads_forgiving(resp2.text)), stages
    except (ValueError, ValidationError) as err2:
        raise SpecParseError(
            f"spec generation failed for {board_id!r} after repair retry: {err2}",
            stages=stages,
        ) from err2


