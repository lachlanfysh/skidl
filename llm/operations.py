"""LLM operations for the overnight PCB-engine corpus runner.

Two operations, both designed so mid-tier (Llama-70B class) models succeed:
rigid prompts, structured JSON outputs, forgiving parsing, and exactly one
repair retry per operation.

- nl_to_input_spec():     marketing text -> CircuitSpec (JSON circuit spec)
- review_exceptions():    structured DesignExceptions -> candidate choices
- external_agent_review(): same review, framed as a third-party API consumer
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Optional

from pydantic import ValidationError

from llm import config
from llm.openrouter_client import complete
from schemas.circuit_spec import CircuitSpec

_REPO_ROOT = Path(__file__).resolve().parent.parent


class SpecParseError(Exception):
    """Spec generation failed after the repair retry. Carries the stage dicts
    (token/cost accounting for both attempts) as ``.stages``."""

    def __init__(self, message: str, stages: list[dict]):
        super().__init__(message)
        self.stages = stages


